"""Latency benchmark: GPU vs CPU vs CPU capped at 4 threads (an edge proxy). Windows dev machine.

For the chosen mode it (re)starts the model-service on :8001 with DEVICE / CPU_THREADS set, then measures
N requests after a warm-up (default N=200, warm-up 20), p50 and p95:
  1. model-service alone: client round trip for POST /v1/embed + the service's own detect / embed timings;
  2. end to end through the gate-service (must be running and seeded): one capture of P001 per event. P001 is set to
     INVALID at mock-idp for the run, so every event takes the FULL path (embed, gallery decrypt + search, 1:1 confirm)
     and ends IDP_REJECTED instead of boarding (repeatable). The final board UPDATE is the only step not exercised;
  3. per-event gallery cost with no plaintext cache (unwrap DEK + DB read + decrypt + dot products), from the
     gate-service's gate_gallery_search_seconds p50/p95 (Micrometer, ~2 min window).
Results go to docs/latency-results.json (one entry per mode) and docs/latency.md (table of all modes run so far).
Usage: python tools/bench_latency.py --device cuda|cpu|cpu4 [-n 200] [--warmup 20]
"""
import argparse
import json
import os
import platform
import re
import statistics
import subprocess
import sys
import time
import uuid
from pathlib import Path

import httpx

from photos import clean_jpeg, find_profile

ROOT = Path(__file__).resolve().parents[1]
MODES = {"cuda": {"DEVICE": "cuda"}, "cpu": {"DEVICE": "cpu"}, "cpu4": {"DEVICE": "cpu", "CPU_THREADS": "4"}}
MODEL_URL, GATE_URL, MOCKS_URL = "http://localhost:8001", "http://localhost:8081", "http://localhost:8002"


def pct(values: list[float]) -> dict:
    s = sorted(values)
    return {"p50": round(statistics.median(s), 1), "p95": round(s[int(0.95 * (len(s) - 1))], 1)}


def start_model_service(mode: str) -> subprocess.Popen:
    env = dict(os.environ)
    env.pop("CPU_THREADS", None)  # only the cpu4 mode sets it
    env.update(MODES[mode])
    proc = subprocess.Popen([sys.executable, "-m", "uvicorn", "app.main:app", "--port", "8001", "--log-level",
                             "warning"], cwd=ROOT / "model-service", env=env,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(120):
        try:
            health = httpx.get(f"{MODEL_URL}/health", timeout=1).json()
            print(f"model-service up: {health['model_id']} on {health['device']} {health['providers']}")
            return proc
        except httpx.HTTPError:
            time.sleep(0.5)
    proc.kill()
    raise SystemExit("model-service did not start (is port 8001 already in use?)")


def timed(fn, n: int, warmup: int) -> tuple[list[float], list]:
    for _ in range(warmup):
        fn()
    times, results = [], []
    for _ in range(n):
        t = time.perf_counter()
        results.append(fn())
        times.append((time.perf_counter() - t) * 1000)
    return times, results


def prometheus_quantiles(metric: str) -> dict:
    text = httpx.get(f"{GATE_URL}/actuator/prometheus", timeout=5).text
    out = {}
    for q, key in (("0.5", "p50"), ("0.95", "p95")):
        m = re.search(rf'^{metric}\{{[^}}]*quantile="{q}"[^}}]*\}} ([0-9.eE+-]+)', text, re.M)
        out[key] = round(float(m.group(1)) * 1000, 2) if m else None
    return out


def hardware() -> dict:
    gpu = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total,driver_version", "--format=csv,noheader"],
                         capture_output=True, text=True).stdout.strip()
    cpu = subprocess.run(["powershell", "-NoProfile", "-Command", "(Get-CimInstance Win32_Processor).Name"],
                         capture_output=True, text=True).stdout.strip()
    return {"gpu": gpu, "cpu": cpu, "os": platform.platform(), "python": platform.python_version()}


def write_markdown(results: dict) -> None:
    hw = next(iter(results.values()))["hardware"]
    lines = ["# Latency results (generated by tools/bench_latency.py)", "",
             f"Hardware: {hw['cpu']}; GPU {hw['gpu']}; {hw['os']}; Python {hw['python']}; onnxruntime-gpu 1.30.0 "
             "(CUDA 13 pip wheels). Probe: one real 899x1599 JPEG with one face; gallery = seeded POC001.", "",
             "| Mode | n | model-service round trip p50 / p95 (ms) | detect p50 / p95 | embed p50 / p95 "
             "| end-to-end decision (client) p50 / p95 | gallery unwrap+decrypt+search p50 / p95 (gallery size) |",
             "|---|---|---|---|---|---|---|"]
    pair = lambda d: f"{d['p50']} / {d['p95']}" if d and d.get("p50") is not None else "not run"
    for mode, r in results.items():
        search = pair(r.get("gallery_search"))
        if search != "not run":
            search += f" ({r['gallery_size']})"
        lines.append(f"| {mode} | {r['n']} | {pair(r['embed_http'])} | {pair(r['detect'])} | {pair(r['embed'])} "
                     f"| {pair(r.get('end_to_end'))} | {search} |")
    lines += ["", "End-to-end = gate_sim-style multipart POST to the gate-service: embed + gallery search + mock-idp "
              "1:1 confirm (local mock, no network latency) + DB write of the gate event. Measured on one desktop; "
              "not a performance claim. cpu4 caps ONNX Runtime intra-op threads at 4 by building the sessions "
              "directly, because InsightFace get_model ignores sess_options (InsightFace issue #2899)."]
    (ROOT / "docs" / "latency.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--device", choices=MODES, required=True)
    ap.add_argument("-n", type=int, default=200)
    ap.add_argument("--warmup", type=int, default=20)
    args = ap.parse_args()

    probe_path = find_profile(ROOT / "data", "P001").probes[0]
    image = clean_jpeg(probe_path)
    proc = start_model_service(args.device)
    try:
        with httpx.Client(base_url=MODEL_URL, timeout=30) as ms:
            post = lambda: ms.post("/v1/embed", content=image, headers={"Content-Type": "image/jpeg"}).json()
            times, bodies = timed(post, args.n, args.warmup)
        result = {"n": args.n, "warmup": args.warmup, "hardware": hardware(), "embed_http": pct(times),
                  "detect": pct([b["timings_ms"]["detect"] for b in bodies]),
                  "embed": pct([b["timings_ms"]["embed"] for b in bodies])}
        print("model-service:", result["embed_http"], "detect", result["detect"], "embed", result["embed"])

        try:
            with httpx.Client(base_url=GATE_URL, timeout=10) as gate, httpx.Client(base_url=MOCKS_URL) as mocks:
                result["gallery_size"] = gate.get("/v1/flights/POC001").json()["active_entries"]
                mocks.put("/admin/profiles/P001/status", json={"status": "INVALID"}).raise_for_status()
                try:
                    def event():
                        r = gate.post("/v1/gates/BENCH/events", data={"flight_id": "POC001"},
                                      files={"image": ("c.jpg", image, "image/jpeg")},
                                      headers={"Idempotency-Key": str(uuid.uuid4())}).json()
                        return r["reason"]
                    times, reasons = timed(event, args.n, args.warmup)
                finally:
                    mocks.put("/admin/profiles/P001/status", json={"status": "VALID"})
            result["end_to_end"] = pct(times)
            result["end_to_end_reasons"] = {r: reasons.count(r) for r in set(reasons)}
            result["gallery_search"] = prometheus_quantiles("gate_gallery_search_seconds")
            print("end to end:", result["end_to_end"], result["end_to_end_reasons"])
            print(f"gallery search ({result['gallery_size']} entries):", result["gallery_search"])
        except (httpx.HTTPError, KeyError) as e:
            print(f"gate-service / mocks not reachable or not seeded ({type(e).__name__}): end-to-end skipped")
    finally:
        proc.terminate()

    store = ROOT / "docs" / "latency-results.json"
    results = json.loads(store.read_text(encoding="utf-8")) if store.exists() else {}
    results[args.device] = result
    results = {m: results[m] for m in MODES if m in results}
    store.write_text(json.dumps(results, indent=2), encoding="utf-8")
    write_markdown(results)
    print(f"written: {store.relative_to(ROOT)}, docs/latency.md")


if __name__ == "__main__":
    main()
